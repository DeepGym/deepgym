"""Write a single-turn DeepGym environment as a Harbor task folder.

The agent writes ``/app/solution.py`` as the unprivileged ``agent`` user, with no network
while it runs. A separate, offline verifier sandbox gets only that file (an artifact) and
runs the environment's own DeepGym verifier, with the solution isolated from it as in any
DeepGym sandbox: tests/test.sh replays the judge setup and runs the solution as its own
user, which can read neither /tests nor the judge's files.
"""

from __future__ import annotations

import json
import shlex
from pathlib import Path, PurePosixPath

from deepgym.exceptions import DeepGymError
from deepgym.judge import (
    SANDBOX_ROOT,
    SANDBOX_SETUP,
    JudgeJob,
    sandbox_judge_by_name,
    sandbox_uploads,
)
from deepgym.models import Environment, MultiTurnEnvironment
from deepgym.sandboxes.cli import DEFAULT_IMAGE

WORKDIR = '/app'
SOLUTION_PATH = f'{WORKDIR}/solution.py'
# Seconds the verifier gets beyond the environment's own budget, for setup and copying.
_SETUP_SLACK_S = 60
_HEREDOC_END = 'DEEPGYM_SOLUTION_EOF'

# The verdict goes to a file only root can replace, and every solver process is gone
# before it's read, so the solution can't plant or rewrite its own reward.
_TEST_SCRIPT = """#!/bin/bash
# Generated by DeepGym: grade {solution} with the environment's DeepGym verifier.
chmod -R go-rwx /tests
rm -f /logs/verifier/reward.json /logs/verifier/reward.txt
mkdir -p /logs/verifier
bash /tests/judge_setup.sh >/dev/null || exit 1
cp -r /tests/deepgym/. {root}/
cp -P {solution} {root}/solution/solution.py 2>/dev/null
chmod -R a+rX {root}/runtime {root}/solution
env {env} {command} > {verdict}
{kill_solver} 2>/dev/null
cp {verdict} /logs/verifier/verifier.out
python3 - {verdict} <<'EOF'
import json, sys
lines = [line.strip() for line in open(sys.argv[1], errors='replace')]
found = [line for line in lines if line.startswith('{{') and line.endswith('}}')]
score = json.loads(found[-1]).get('score') if found else None
if type(score) in (int, float) and 0 <= score <= 1:
    open('/logs/verifier/reward.txt', 'w').write(f'{{float(score)}}\\n')
EOF
"""

_DOCKERFILE = """FROM {image}
RUN useradd --create-home agent && mkdir -p {workdir} && chown agent:agent {workdir}
WORKDIR {workdir}
"""


def export_environment(env: Environment | MultiTurnEnvironment, out_dir: Path) -> Path:
    """Write *env* as a Harbor task folder named after it inside *out_dir*.

    Args:
        env: A single-turn environment with its own verifier.
        out_dir: Parent folder; created if missing.

    Returns:
        The new task folder.

    Raises:
        DeepGymError: If *env* is multi-turn, unnamed, benchmark-backed or a Harbor task
            already, if the folder exists, or if its reference solution contains the
            heredoc marker.
    """
    if not isinstance(env, Environment):
        raise DeepGymError(f'{env.name} is multi-turn; only single-turn envs export')
    if hasattr(env, 'run_with_deepgym') or hasattr(env, 'prepare_batch_requests'):
        raise DeepGymError(f'{env.name} scores itself, so it has no verifier to export')
    if not env.name or PurePosixPath(env.name).name != env.name or env.name in ('.', '..'):
        raise DeepGymError(f'Cannot name a task folder {env.name!r}')
    task_dir = out_dir / env.name
    if task_dir.exists():
        raise DeepGymError(f'{task_dir} already exists; remove it to export again')
    files = {
        'instruction.md': (
            f'{env.task.rstrip()}\n\nWrite your solution as a Python module at `{SOLUTION_PATH}`.\n'
        ),
        'task.toml': _task_toml(env),
        'environment/Dockerfile': _DOCKERFILE.format(
            image=env.image or DEFAULT_IMAGE, workdir=WORKDIR
        ),
        **_test_files(env),
    }
    if env.reference_solution is not None:
        files['solution/solve.sh'] = _solve_script(env.reference_solution)
    for rel, content in files.items():
        path = task_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
    return task_dir


def _task_toml(env: Environment) -> str:
    """task.toml: separate offline verifier, non-root offline agent, the solution as artifact."""

    def text(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    return '\n'.join(
        [
            'schema_version = "1.3"',
            f'artifacts = [{text(SOLUTION_PATH)}]',
            '',
            '[task]',
            f'name = {text(f"deepgym/{env.name}")}',
            '',
            '[metadata]',
            f'difficulty = {text(env.difficulty)}',
            f'category = {text(env.domain)}',
            f'tags = [{", ".join(map(text, env.tags))}]',
            '',
            '[agent]',
            'user = "agent"',
            'network_mode = "no-network"',
            '',
            '[verifier]',
            f'timeout_sec = {env.timeout + _SETUP_SLACK_S}',
            'environment_mode = "separate"',
            '',
            '[verifier.environment]',
            'network_mode = "no-network"',
            '',
            '[environment]',
            f'workdir = {text(WORKDIR)}',
            '',
        ]
    )


def _test_files(env: Environment) -> dict[str, str]:
    """tests/: test.sh, the judge's setup script, and the judge files under deepgym/."""
    job = JudgeJob.for_environment(env, '')
    command, judge_env = sandbox_judge_by_name(job)
    files = {
        f'tests/deepgym/{PurePosixPath(path).relative_to(SANDBOX_ROOT)}': content.decode('utf-8')
        for content, path in sandbox_uploads(job)
    }
    files['tests/judge_setup.sh'] = SANDBOX_SETUP
    solver = json.loads(judge_env['DEEPGYM_ISOLATION'])['prefix']
    files['tests/test.sh'] = _TEST_SCRIPT.format(
        solution=shlex.quote(SOLUTION_PATH),
        root=shlex.quote(SANDBOX_ROOT),
        env=' '.join(shlex.quote(f'{key}={value}') for key, value in judge_env.items()),
        command=command,
        verdict=shlex.quote(f'{SANDBOX_ROOT}/verdict.out'),
        kill_solver=shlex.join([*solver, 'sh', '-c', 'kill -9 -1']),
    )
    return files


def _solve_script(reference: str) -> str:
    """solution/solve.sh: write the reference solution to the solution path.

    Raises:
        DeepGymError: If *reference* has a line equal to the heredoc's end marker.
    """
    if _HEREDOC_END in reference.splitlines():
        raise DeepGymError(f'The reference solution contains the line {_HEREDOC_END}')
    body = reference.rstrip('\n')
    target = shlex.quote(SOLUTION_PATH)
    return f"#!/bin/bash\ncat > {target} <<'{_HEREDOC_END}'\n{body}\n{_HEREDOC_END}\n"
