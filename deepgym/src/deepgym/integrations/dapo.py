"""DAPO integration built on top of DeepGym's reward engine.

DAPO is commonly run through ``verl`` recipes rather than a standalone trainer
API. DeepGym keeps the integration thin: expose reward callbacks and helper
config/module generators that fit naturally into an external DAPO training run.

The callbacks take completions plus per-sample metadata, as TRL's do, and are TRL's
(:mod:`deepgym.integrations.trl`): the last fenced code block of each completion runs,
and a completion that got no verdict (a sandbox or verifier failure) is rewarded None
rather than 0.0, so your loop can leave it out of the loss and of its group's statistics.
"""

from __future__ import annotations

from pathlib import Path

from deepgym.integrations.trl import make_trl_async_reward_fn, make_trl_reward_fn

make_dapo_reward_fn = make_trl_reward_fn
make_dapo_async_reward_fn = make_trl_async_reward_fn
# One reward function per reward component: pass component='correctness' and so on.
make_dapo_shaped_reward_fn = make_trl_reward_fn

_AGENT_LOOPS = Path(__file__).with_name('verl_agent_loops.yaml')
"""verl agent loop config listing ``deepgym_single_turn``, shipped with the package."""

_DAPO_VERL_CONFIG_TEMPLATE = """\
# verl DAPO config with DeepGym reward scoring
# Generated by deepgym.integrations.dapo
#
# verl runs DAPO as GRPO advantages. DeepGym's deepgym_single_turn agent loop scores
# each sample with the reward function below and keeps one whose sandbox or verifier
# failed out of training (deepgym.integrations.verl_mask). verl's reward manager, and
# with it DAPO's overlong penalty, doesn't run on samples the loop scored. The default
# reward function is DeepGym's compute_score, and dataset rows name their environment
# in extra_info.environment (see deepgym.integrations.verl.verl_rows).

algorithm:
  adv_estimator: grpo

data:
  train_files: {train_files}
  val_files: {val_files}
  prompt_key: {prompt_key}

actor_rollout_ref:
  rollout:
    n: {samples_per_prompt}
    agent:
      agent_loop_config_path: {agent_loop_config_path}
      default_agent_loop: deepgym_single_turn

reward:
  custom_reward_function:
    path: {reward_module_path}
    name: {reward_fn_name}

trainer:
  project_name: {project_name}
  default_local_dir: {output_dir}
  total_epochs: {epochs}
"""


def generate_dapo_verl_config(
    *,
    train_files: str,
    reward_module_path: str = 'pkg://deepgym.integrations.verl',
    reward_fn_name: str = 'compute_score',
    output_dir: str = 'outputs/dapo',
    val_files: str = '',
    prompt_key: str = 'prompt',
    epochs: int = 1,
    samples_per_prompt: int = 8,
    project_name: str = 'deepgym-dapo',
) -> str:
    """Generate a minimal verl DAPO config snippet that scores with DeepGym.

    The config selects DeepGym's ``deepgym_single_turn`` agent loop
    (:mod:`deepgym.integrations.verl_mask`, listed in a config file that ships with
    deepgym), which keeps a sample that got no verdict out of training. It scores with
    :func:`deepgym.integrations.verl.compute_score` by default; pass the path of a module
    from :func:`generate_dapo_reward_module` to pin one environment instead.
    """
    return _DAPO_VERL_CONFIG_TEMPLATE.format(
        train_files=train_files,
        val_files=val_files or train_files,
        prompt_key=prompt_key,
        agent_loop_config_path=_AGENT_LOOPS,
        reward_module_path=reward_module_path,
        reward_fn_name=reward_fn_name,
        output_dir=output_dir,
        epochs=epochs,
        samples_per_prompt=samples_per_prompt,
        project_name=project_name,
    )


_DAPO_REWARD_MODULE_TEMPLATE = """\
from deepgym import load_environment
from deepgym.integrations.verl import make_verl_compute_score

compute_score = make_verl_compute_score(load_environment({env_name!r}))
"""


def generate_dapo_reward_module(env_name: str) -> str:
    """Generate a reward module that scores every verl sample with one environment.

    The agent loop :func:`generate_dapo_verl_config` selects scores with it, so a sample
    without a verdict is kept out of training.
    """
    return _DAPO_REWARD_MODULE_TEMPLATE.format(env_name=env_name)
